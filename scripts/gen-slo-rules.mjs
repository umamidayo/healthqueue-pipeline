#!/usr/bin/env node
// Generates Prometheus recording + multi-window, multi-burn-rate alerting
// rules from observability/slo-spec.json.
//
// The burn-rate thresholds follow the Google SRE Workbook ("Alerting on SLOs",
// table 5-8) for a 30-day window:
//   page   : 2% of budget in 1h (14.4x) or 5% in 6h (6x)
//   ticket : 10% of budget in 3d (1x)  or 10% in 1d (3x)
// Each long window is paired with a short window (1/12 of it) so alerts reset
// quickly once the problem stops.
//
// Usage: node scripts/gen-slo-rules.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const specPath = join(root, 'observability', 'slo-spec.json');
const outPath = join(root, 'deploy', 'components', 'monitoring', 'slo-rules.yaml');

const BURN_ALERTS = [
  { severity: 'page', windows: [['1h', '5m', 14.4], ['6h', '30m', 6]], for: '2m' },
  { severity: 'ticket', windows: [['1d', '2h', 3], ['3d', '6h', 1]], for: '15m' },
];
const FAST_WINDOWS = ['5m', '30m', '1h', '2h', '6h'];
const SLOW_WINDOWS = ['1d', '3d'];

const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const indent = (text, n) => text.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');
const camel = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const recordName = (slo, w) => `${spec.service.replace(/-/g, '_')}:slo_${slo.name}_errors:ratio_rate${w}`;

function ratioExpr(slo, window) {
  const errors = slo.errorQuery.replaceAll('$window', window);
  const total = slo.totalQuery.replaceAll('$window', window);
  // `or 0 * total` keeps the ratio at 0 (instead of absent) before the first
  // error is ever recorded, so dashboards and absent()-style checks behave.
  return `(\n  (${errors})\n  or\n  (0 * ${total})\n)\n/\n${total}`;
}

function recordingRule(slo, w) {
  return `- record: ${recordName(slo, w)}\n  expr: |\n${indent(ratioExpr(slo, w), 4)}\n  labels:\n    slo: ${slo.name}`;
}

function alertRule(slo, alert) {
  const budget = Number((1 - slo.objective / 100).toFixed(6));
  const clauses = alert.windows.map(
    ([long, short, factor]) =>
      `(\n  ${recordName(slo, long)} > (${factor} * ${budget})\n  and\n  ${recordName(slo, short)} > (${factor} * ${budget})\n)`,
  );
  const speed = alert.severity === 'page' ? 'Fast' : 'Slow';
  const windowsText = alert.windows.map(([l, s, f]) => `${f}x over ${l}/${s}`).join(' or ');
  return [
    `- alert: HealthQueue${camel(slo.name)}BudgetBurn${speed}`,
    `  expr: |`,
    indent(clauses.join('\nor\n'), 4),
    `  for: ${alert.for}`,
    `  labels:`,
    `    severity: ${alert.severity}`,
    `    slo: ${slo.name}`,
    `  annotations:`,
    `    summary: "${spec.service} ${slo.name} SLO error budget is burning too fast in {{ $labels.namespace }}"`,
    `    description: "${slo.description} Objective ${slo.objective}% over ${spec.windowDays}d. Burn condition: ${windowsText}."`,
    `    runbook_url: ${spec.runbookUrl}`,
  ].join('\n');
}

function budgetRule(slo) {
  const budget = Number((1 - slo.objective / 100).toFixed(6));
  return [
    `- record: ${spec.service.replace(/-/g, '_')}:slo_${slo.name}_error_budget:remaining_ratio`,
    `  expr: |`,
    `    1 - (${recordName(slo, `${spec.windowDays}d`)} / ${budget})`,
    `  labels:`,
    `    slo: ${slo.name}`,
  ].join('\n');
}

const groups = [];
for (const slo of spec.slos) {
  groups.push({
    name: `slo-${slo.name}-fast`,
    interval: '30s',
    rules: FAST_WINDOWS.map((w) => recordingRule(slo, w)),
  });
  // Long windows are expensive to evaluate and change slowly.
  groups.push({
    name: `slo-${slo.name}-slow`,
    interval: '5m',
    rules: [...SLOW_WINDOWS, `${spec.windowDays}d`].map((w) => recordingRule(slo, w)).concat(budgetRule(slo)),
  });
  groups.push({ name: `slo-${slo.name}-alerts`, rules: BURN_ALERTS.map((a) => alertRule(slo, a)) });
}

groups.push({
  name: 'healthqueue-availability',
  rules: [
    [
      '- alert: HealthQueueTargetDown',
      '  expr: |',
      `    sum by (namespace) (up{job="${spec.service}"}) == 0`,
      '  for: 5m',
      '  labels:',
      '    severity: page',
      '  annotations:',
      `    summary: "No ${spec.service} targets are up in {{ $labels.namespace }}"`,
      '    description: "Prometheus cannot scrape any API pod. SLO metrics are blind until this resolves."',
      `    runbook_url: ${spec.runbookUrl}`,
    ].join('\n'),
  ],
});

const body = groups
  .map((g) => {
    const head = [`- name: ${g.name}`];
    if (g.interval) head.push(`  interval: ${g.interval}`);
    head.push('  rules:');
    return `${head.join('\n')}\n${indent(g.rules.join('\n'), 4)}`;
  })
  .join('\n');

const output = `# GENERATED by scripts/gen-slo-rules.mjs from observability/slo-spec.json.
# Do not edit by hand; CI fails when this file is out of date.
apiVersion: monitoring.coreos.com/v1
kind: PrometheusRule
metadata:
  name: healthqueue-api-slos
spec:
  groups:
${indent(body, 4)}
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n');
  if (current !== output) {
    console.error(`${outPath} is stale. Run: node scripts/gen-slo-rules.mjs`);
    process.exit(1);
  }
  console.log('SLO rules are up to date');
} else {
  writeFileSync(outPath, output);
  console.log(`wrote ${outPath}`);
}
