import { formatHours, formatPct, isoDate } from './stats.mjs';

const BAND_LABEL = { elite: 'Elite', high: 'High', medium: 'Medium', low: 'Low' };
const band = (b) => (b ? BAND_LABEL[b] : 'n/a');

function trend(first, last, lowerIsBetter) {
  if (first === null || last === null || first === undefined || last === undefined) return 'n/a';
  if (first === 0 && last === 0) return 'flat';
  const delta = first === 0 ? 1 : (last - first) / Math.abs(first);
  if (Math.abs(delta) < 0.05) return 'flat';
  const better = lowerIsBetter ? delta < 0 : delta > 0;
  return `${better ? 'improving' : 'worsening'} (${delta > 0 ? '+' : ''}${(delta * 100).toFixed(0)}%)`;
}

export function renderMarkdown({ dataset, metrics, toil }) {
  const o = metrics.overall;
  const c = metrics.comparison;
  const L = [];
  const synthetic = dataset.source === 'synthetic';

  L.push(`# DORA report: ${dataset.repo}`);
  L.push('');
  if (synthetic) {
    L.push('> **Synthetic data.** Generated by `node dora/cli.mjs sample` to demonstrate the report. Numbers describe no real team.');
    L.push('');
  }
  L.push(
    `Window **${isoDate(dataset.window.start)} to ${isoDate(dataset.window.end)}** (${dataset.window.days} days) · source \`${dataset.source}\` · generated ${dataset.generatedAt}`,
  );
  L.push('');

  L.push('## Summary');
  L.push('');
  L.push('| Metric | Value | Indicative band | First 30d to last 30d |');
  L.push('|---|---|---|---|');
  L.push(
    `| Deployment frequency | ${o.deploymentFrequency.perWeek.toFixed(1)}/week (${o.deploymentFrequency.deployments} deploys, ${o.deploymentFrequency.activeDays} active days) | ${band(o.deploymentFrequency.band)} | ${c ? trend(c.first30.deploymentFrequency.perDay, c.last30.deploymentFrequency.perDay, false) : 'n/a'} |`,
  );
  L.push(
    `| Change lead time | p50 ${formatHours(o.leadTime.p50Hours)}, p90 ${formatHours(o.leadTime.p90Hours)} (${o.leadTime.changes} changes) | ${band(o.leadTime.band)} | ${c ? trend(c.first30.leadTime.p50Hours, c.last30.leadTime.p50Hours, true) : 'n/a'} |`,
  );
  L.push(
    `| Change fail rate | ${formatPct(o.changeFailRate.rate)} (${o.changeFailRate.failed}/${o.changeFailRate.total}) | ${band(o.changeFailRate.band)} | ${c ? trend(c.first30.changeFailRate.rate, c.last30.changeFailRate.rate, true) : 'n/a'} |`,
  );
  L.push(
    `| Failed deployment recovery time | p50 ${formatHours(o.recoveryTime.p50Hours)}, p90 ${formatHours(o.recoveryTime.p90Hours)} (${o.recoveryTime.samples} samples) | ${band(o.recoveryTime.band)} | ${c ? trend(c.first30.recoveryTime.p50Hours, c.last30.recoveryTime.p50Hours, true) : 'n/a'} |`,
  );
  L.push(
    `| Deployment rework rate | ${formatPct(o.reworkRate.rate)} (${o.reworkRate.rework}/${o.reworkRate.total}) | n/a | ${c ? trend(c.first30.reworkRate.rate, c.last30.reworkRate.rate, true) : 'n/a'} |`,
  );
  L.push('');
  L.push(
    `Incidents in window: ${o.incidents.total} (${o.incidents.attributed} attributed to a deployment, ${o.incidents.open} still open).`,
  );
  L.push('');

  L.push('## Weekly trend');
  L.push('');
  L.push('| Week of | Deploys | Lead time p50 | Failed | Change fail rate | Recovery p50 |');
  L.push('|---|---:|---:|---:|---:|---:|');
  for (const w of metrics.weekly) {
    L.push(
      `| ${w.weekStart} | ${w.deployments} | ${formatHours(w.leadTimeP50Hours)} | ${w.failed} | ${formatPct(w.changeFailRate)} | ${formatHours(w.recoveryP50Hours)} |`,
    );
  }
  L.push('');

  const s = toil.signals;
  const t = toil.targets;
  L.push('## Toil and flow signals');
  L.push('');
  L.push('| Signal | Observed | Target |');
  L.push('|---|---:|---:|');
  L.push(`| Manual CI re-run rate | ${formatPct(s.rerunRate)} | <= ${formatPct(t.rerunRate)} |`);
  L.push(`| PR CI duration p90 | ${s.prCiP90Minutes?.toFixed(1) ?? 'n/a'} min | <= ${t.prCiP90Minutes} min |`);
  L.push(`| Merge to staging p90 | ${s.mainToStagingP90Minutes?.toFixed(1) ?? 'n/a'} min | <= ${t.mainToStagingP90Minutes} min |`);
  L.push(`| Time to first review p50 | ${formatHours(s.reviewWaitP50Hours)} | <= ${t.reviewWaitP50Hours}h |`);
  L.push(`| Staging to production wait p50 | ${formatHours(s.promotionWaitP50Hours)} | <= ${t.promotionWaitP50Hours}h |`);
  L.push(`| Human commits per deploy (median) | ${s.batchSizeMedian ?? 'n/a'} | <= ${t.batchSizeMedian} |`);
  L.push(`| Dependency-bot PRs merged | ${s.botPrsPerMonth.toFixed(1)}/month | auto-merge |`);
  L.push(`| Incident person-hours | ${s.incidentPersonHoursPerMonth.toFixed(1)}/month | trending down |`);
  L.push('');

  L.push('## Toil reduction recommendations');
  L.push('');
  if (toil.recommendations.length === 0) {
    L.push('No signal is near its target. Keep the current practices and re-check next run.');
  } else {
    L.push(
      `Ranked by priority, then estimated impact per unit of effort. Recoverable manual toil: **~${toil.totals.toilHoursPerMonth.toFixed(1)} engineer-hours/month**.`,
    );
    L.push('');
    toil.recommendations.forEach((r, i) => {
      const gains = [];
      if (r.toilHoursPerMonth) gains.push(`~${r.toilHoursPerMonth.toFixed(1)} engineer-h/month`);
      if (r.leadTimeHoursSaved > 0) gains.push(`~${r.leadTimeHoursSaved.toFixed(0)} change-hours of waiting/month`);
      L.push(`### ${i + 1}. ${r.title}`);
      L.push('');
      L.push(`**${r.priority}** · ${r.category} · effort ${r.effort}${gains.length ? ` · ${gains.join(', ')}` : ''}`);
      L.push('');
      L.push(`Evidence: ${r.evidence}`);
      L.push('');
      for (const a of r.actions) L.push(`- ${a}`);
      L.push('');
    });
  }

  L.push('## Method and caveats');
  L.push('');
  L.push('- Definitions and data sources: `docs/dora.md`. Bands use the 2023 DORA thresholds as orientation only.');
  L.push(
    `- Cost model (edit with \`--costs\`): re-run ${toil.costs.rerunMinutes} min, promotion ${toil.costs.promotionMinutes} min, bot PR ${toil.costs.botPrMinutes} min, ${toil.costs.incidentResponders} responders per incident, CI-wait attention factor ${toil.costs.waitAttentionFactor}.`,
  );
  for (const n of dataset.notes ?? []) L.push(`- ${n}`);
  L.push('');
  return L.join('\n');
}
